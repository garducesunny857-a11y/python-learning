dream_Place = ["tokyo", "paris", "new york", "sydney", "cape town"]

print("\nThis is the original list")
print(dream_Place)

print("\nThis is the sorted list")
print(sorted(dream_Place))

print("\nthis is the original list again")
print(dream_Place)

print("\nThis is the reverse sorted list")
print(sorted(dream_Place, reverse=True))

print("\nThis is the original list again")
print(dream_Place)

print("\nThis is the revised original list again")
dream_Place.reverse()
print(dream_Place)

print("\nThis is the revised original list again")
dream_Place.reverse()
print(dream_Place)

print("\nThis is the sort list ")
dream_Place.sort()
print(dream_Place)

print("\nThis is the reverse sort list ")
dream_Place.sort(reverse=True)
